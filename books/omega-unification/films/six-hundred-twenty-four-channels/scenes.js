function chShell() {
  const P = [];
  for (let x = 0; x * x <= CH_R; x++) for (let y = 0; x * x + y * y <= CH_R; y++) {
    const z2 = CH_R - x * x - y * y, z = Math.round(Math.sqrt(z2));
    if (z * z === z2) P.push([x, y, z]);
  }
  return P;
}
