/* response_iff, both sides over Z/p */
function chSchurSides(p, T) {
  const md = x => ((x % p) + p) % p, key = (b, g, e, z) => ((b * p + g) * p + e) * p + z;
  const img = new Set();
  for (const t of T) for (let a = 0; a < p; a++) for (let b = 0; b < p; b++) for (let d = 0; d < p; d++)
    for (let e = 0; e < p; e++) for (let f = 0; f < p; f++)
      img.add(key(md(-b * d * t), md(-d * (e + t * f)), md(-a * (e + t * f)), md(-b * (t * e + f))));
  const rhs = (B, G, E, Z) => (T.includes(0) && B === 0) ||
    (T.some(t => t !== 0) && (B !== 0 || G === 0 || Z === 0) && (G !== 0 || B === 0 || E === 0));
  let bad = 0;
  for (let B = 0; B < p; B++) for (let G = 0; G < p; G++) for (let E = 0; E < p; E++) for (let Z = 0; Z < p; Z++)
    if (img.has(key(B, G, E, Z)) !== rhs(B, G, E, Z)) bad++;
  return bad;
}
/* ScalarGramAdmissible a b c d, transcribed from the theorem's four clauses */
function chAdmissible(a, b, c, d) {
  if (b === 0 || c === 0) return true;
  if (b <= a && c <= d) return true;
  if (a < b && ((2 * b <= 3 * a && 3 * c <= 2 * d) || (3 * a < 2 * b && b <= 2 * a && 2 * c <= d) || (2 * a < b && b <= 3 * a && 3 * c <= d))) return true;
  if (d < c && ((2 * c <= 3 * d && 3 * b <= 2 * a) || (3 * d < 2 * c && c <= 2 * d && 2 * b <= a) || (2 * d < c && c <= 3 * d && 3 * b <= a))) return true;
  return false;
}
