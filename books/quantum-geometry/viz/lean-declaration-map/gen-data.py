#!/usr/bin/env python3
"""Generate the data of the LEAN//MAP page from trureturing.lock.json and the Chinese chapters.

    python3 books/quantum-geometry/viz/lean-declaration-map/gen-data.py

The page contract lets a visualization load only its own main.js, so the data is written into main.js between the
markers `/* <generated by gen-data.py> */` and `/* </generated> */`. Nothing in that block is typed by hand:

  * every declaration of the lock (its GID, kind and source line), in the order of the lock;
  * every place a Chinese chapter cites it: an environment attribute `lean="<GID> …"` on a `:::` line, or an inline
    link `(lean:<GID>)` / `<lean:<GID>>`; units are taken in the reading order of zh/SUMMARY.md;
  * its serial number in the index of Appendix C (`T…`, `D…`, `R…`), read from the first column of that table.

Run it again whenever the lock or the chapters change, and commit main.js.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
BOOK = ROOT / "books" / "quantum-geometry"
MAIN = HERE / "main.js"
BEGIN, END = "/* <generated by gen-data.py> */", "/* </generated> */"
KINDS = ["theorem", "def", "inductive"]
INDEX = "appendix-c.md"

# the column labels of the stage (short enough for a column 12 px wide)
CN_NUM = "零一二三四五六七八九十"


def cn_number(n: int) -> str:
    if n <= 10:
        return CN_NUM[n]
    if n < 20:
        return "十" + (CN_NUM[n - 10] if n > 10 else "")
    return CN_NUM[n // 10] + "十" + (CN_NUM[n % 10] if n % 10 else "")


def units_and_parts(lang: str):
    """Reading order of a SUMMARY.md: [(file, title, part index)], [part title]."""
    text = (BOOK / lang / "SUMMARY.md").read_text(encoding="utf-8")
    units, parts, part = [], [], -1
    for line in text.splitlines():
        h = re.match(r"^# (.+)$", line)
        if h and not line.startswith("# Summary"):
            parts.append(h.group(1).strip())
            part = len(parts) - 1
            continue
        m = re.search(r"\[(.+)\]\(([^)]+\.md)\)", line)
        if m:
            units.append((m.group(2), m.group(1), part))
    return units, parts


def main() -> int:
    lock = json.loads((ROOT / "trureturing.lock.json").read_text(encoding="utf-8"))
    decls = lock["declarations"]
    units_zh, parts_zh = units_and_parts("zh")
    units_en, parts_en = units_and_parts("en")
    assert [u[0] for u in units_zh] == [u[0] for u in units_en], "zh and en SUMMARY.md list different files"

    cites = {gid: [] for gid in decls}          # gid -> [[unit, 'e' | 'i'], …]
    for ui, (file, _, _) in enumerate(units_zh):
        text = (BOOK / "zh" / file).read_text(encoding="utf-8")
        env, inline = set(), set()
        for line in text.splitlines():
            if line.startswith(":::"):
                for attr in re.findall(r'\slean="([^"]*)"', line):
                    env.update(g for g in re.split(r"[\s,]+", attr.strip()) if g)
        for m in re.finditer(r"\(lean:([^)\s]+)\)|<lean:([^>\s]+)>", text):
            inline.add(m.group(1) or m.group(2))
        for gid in env | inline:
            if gid not in decls:
                if gid in env:
                    raise SystemExit(f"{file}: lean=\"{gid}\" is not in trureturing.lock.json")
                continue                         # e.g. the placeholder `lean:GID` in prose
            cites[gid].append([ui, "e" if gid in env else "i"])

    index_text = (BOOK / "zh" / INDEX).read_text(encoding="utf-8")
    serial = {g: s for s, g in re.findall(r"^\| `([TDR]\d+)` \| \[[^\]]*\]\(lean:([^)\s]+)\)", index_text, re.M)}

    index_unit = [u[0] for u in units_zh].index(INDEX)
    rows, missing = [], []
    for gid, d in decls.items():
        body = [c for c in cites[gid] if c[0] != index_unit]
        if not body:
            missing.append(gid)
        home = min(c[0] for c in body) if body else index_unit
        rows.append([gid, KINDS.index(d["kind"]), d.get("line") or 0, home, sorted(cites[gid]), serial.get(gid, "")])
    if missing:
        print(f"note: {len(missing)} declarations are cited only in {INDEX}", file=sys.stderr)

    def label(file, title, lang):
        m = re.match(r"ch(\d+)-", file)
        if m:
            n = int(m.group(1))
            return [str(n), f"第{cn_number(n)}章" if lang == "zh" else f"Chapter {n}"]
        if file == "README.md":
            return ["0", "序曲" if lang == "zh" else "Prelude"]
        if file == "coda.md":
            return ["终" if lang == "zh" else "Co", "终章" if lang == "zh" else "Coda"]
        m = re.match(r"appendix-([a-z])\.md", file)
        letter = m.group(1).upper()
        return [letter, f"附录 {letter}" if lang == "zh" else f"Appendix {letter}"]

    units = []
    for (file, tzh, part), (_, ten, _) in zip(units_zh, units_en):
        szh, nzh = label(file, tzh, "zh")
        sen, nen = label(file, ten, "en")
        units.append({"file": file, "part": part, "s": [szh, sen], "n": [nzh, nen]})
    parts = [[a.split(" ")[0], " ".join(b.split(" ")[:2]) if b.startswith("Part ") else b] for a, b in zip(parts_zh, parts_en)]

    data = {"repo": lock["repo"], "commit": lock["commit"], "kinds": KINDS, "index": index_unit,
            "units": units, "parts": parts, "decls": rows}
    block = f"{BEGIN}\nconst DATA = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n{END}"
    src = MAIN.read_text(encoding="utf-8")
    if BEGIN not in src or END not in src:
        raise SystemExit(f"{MAIN}: markers {BEGIN} … {END} not found")
    head, rest = src.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    MAIN.write_text(head + block + tail, encoding="utf-8")

    kinds = {k: sum(1 for r in rows if r[1] == i) for i, k in enumerate(KINDS)}
    env = sum(1 for r in rows if any(c[1] == "e" for c in r[4]))
    print(f"{len(rows)} declarations {kinds}; {env} cited by a lean= environment, {len(rows) - env} only inline; "
          f"{len(units)} units, {len(parts)} parts; {sum(1 for r in rows if r[5])} with an Appendix C serial")
    return 0


if __name__ == "__main__":
    sys.exit(main())
