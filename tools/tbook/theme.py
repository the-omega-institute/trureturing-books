"""``./tbook theme``: derive every renderer's palette from ``theme/tokens.json``.

Outputs (committed, checked by ``./tbook check``):

* ``theme/generated/tokens.css`` — CSS custom properties. ``:root`` holds the screen
  (dark neon) palette as ``--tr-*``; ``.tr-paper`` / ``[data-tr-palette=paper]`` swap in
  the paper palette. Used by mdBook, EPUB, the site hub, visualizations and slides.
* ``theme/generated/tokens.typ`` — Typst dictionaries ``tr-screen`` / ``tr-paper`` /
  ``tr-fonts`` for the PDF template.
* ``theme/generated/tokens.mjs`` — ES module for canvas code (viz, film, slides).
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from . import paths

HEADER = "generated by ./tbook theme from theme/tokens.json — do not edit"


def load_tokens() -> dict:
    return json.loads(paths.TOKENS.read_text(encoding="utf-8"))


def _css_font(stack: list[str]) -> str:
    return ", ".join(f'"{f}"' if " " in f or f[0].isupper() else f for f in stack)


def css(tokens: dict) -> str:
    out = [f"/* {HEADER} */", ":root {", "  color-scheme: dark;"]
    for k, v in tokens["screen"].items():
        out.append(f"  --tr-{k}: {v};")
    for k, v in tokens["semantic"].items():
        out.append(f"  --tr-sem-{k}: var(--tr-{v});")
    for k, v in tokens["font"].items():
        if isinstance(v, list):
            out.append(f"  --tr-font-{k}: {_css_font(v)};")
    for k, v in tokens["effect"].items():
        out.append(f"  --tr-fx-{k}: {v};")
    out.append("}")
    out.append(".tr-paper, [data-tr-palette=\"paper\"] {")
    out.append("  color-scheme: light;")
    for k, v in tokens["paper"].items():
        out.append(f"  --tr-{k}: {v};")
    out.append("}")
    out.append("")
    return "\n".join(out)


def _typ_str(v: str) -> str:
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _typ_color(v: str) -> str:
    v = v.strip()
    if v.startswith("#"):
        return f"rgb({_typ_str(v)})"
    m = re.match(r"rgba?\(([^)]*)\)", v)
    if m:
        parts = [p.strip() for p in m.group(1).split(",")]
        r, g, b = (int(float(p)) for p in parts[:3])
        a = float(parts[3]) if len(parts) > 3 else 1.0
        return f"rgb({r}, {g}, {b}, {round(a * 100)}%)"
    raise ValueError(f"unsupported colour {v!r}")


def typst(tokens: dict) -> str:
    out = [f"// {HEADER}"]
    for name in ("screen", "paper", "film"):
        out.append(f"#let tr-{name} = (")
        for k, v in tokens[name].items():
            out.append(f"  {_typ_str(k)}: {_typ_color(v)},")
        out.append(")")
    out.append("#let tr-semantic = (")
    for k, v in tokens["semantic"].items():
        out.append(f"  {_typ_str(k)}: {_typ_str(v)},")
    out.append(")")
    out.append("#let tr-fonts = (")
    for k, v in tokens["font"].items():
        if isinstance(v, list):
            out.append(f"  {_typ_str(k)}: (" + ", ".join(_typ_str(f) for f in v) + ",),")
    out.append(")")
    out.append("")
    return "\n".join(out)


def js(tokens: dict) -> str:
    data = {k: tokens[k] for k in ("screen", "paper", "film", "semantic", "font", "effect")}
    body = json.dumps(data, ensure_ascii=False, indent=2)
    return f"// {HEADER}\nexport const TOKENS = {body};\nexport default TOKENS;\n"


def outputs() -> dict[Path, str]:
    tokens = load_tokens()
    return {
        paths.GENERATED / "tokens.css": css(tokens),
        paths.GENERATED / "tokens.typ": typst(tokens),
        paths.GENERATED / "tokens.mjs": js(tokens),
    }


def write() -> list[Path]:
    written = []
    for path, text in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            written.append(path)
    return written


def stale_outputs() -> list[Path]:
    return [p for p, text in outputs().items() if not p.exists() or p.read_text(encoding="utf-8") != text]
