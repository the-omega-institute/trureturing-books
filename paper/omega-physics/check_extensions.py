"""Numerical sanity checks for the extension sections (not a proof)."""
import numpy as np, itertools
rng = np.random.default_rng(11)
def cunit(n):
    v = rng.normal(size=n) + 1j*rng.normal(size=n); return v/np.linalg.norm(v)
def real(v): return np.concatenate([v.real, v.imag])
def rip(a, b): return float(np.real(np.vdot(a, b)))        # real inner product on C^n = R^2n
def refl(x, w): return 2*rip(x, w)*x - w                    # s_x(w)
def schmidt(v): return np.linalg.svd(v.reshape(2, 2), compute_uv=False)

# --- A. round trips force entanglement -------------------------------------------------
k0 = np.array([1, 0], complex); plus = np.array([1, 1], complex)/np.sqrt(2)
z = refl(np.kron(k0, k0), np.kron(plus, plus))
print("A1 mirror of |++> in |00>: norm %.6f, Schmidt coeffs" % np.linalg.norm(z), np.round(schmidt(z), 6))
# product transport violates the round-trip law for the composite kernel
bad = 0.0
for _ in range(200):
    x1, x2, w1, w2 = (cunit(2) for _ in range(4))
    x, w = np.kron(x1, x2), np.kron(w1, w2)
    prod = np.kron(refl(x1, w1), refl(x2, w2))
    kap = lambda a, b: (1 + rip(a, b))/2
    bad = max(bad, abs(kap(w, prod) - (2*kap(w, x) - 1)**2))
    assert abs(kap(w, refl(x, w)) - (2*kap(w, x) - 1)**2) < 1e-12
print("A2 product transport: max violation of round-trip law = %.3f (linear reflection: 0)" % bad)
# Lie algebra generated by rotations inside the local great spheres E_k(x)
def wedge(a, b): return np.outer(a, b) - np.outer(b, a)
def lie_closure(gens, n):
    basis = []
    def add(m):
        v = m.reshape(-1)
        for b in basis: v = v - (v @ b)*b
        nv = np.linalg.norm(v)
        if nv > 1e-8: basis.append(v/nv); return True
        return False
    mats = []
    for g in gens:
        if add(g): mats.append(g)
    changed = True
    while changed:
        changed = False
        for a, b in itertools.combinations(list(mats), 2):
            c = a@b - b@a
            if add(c): mats.append(c); changed = True
        if len(basis) >= n*(n-1)//2: break
    return len(basis)
gens = []
for _ in range(6):
    x1, x2 = cunit(2), cunit(2)
    for k in range(2):
        E = []
        for e in (np.array([1, 0], complex), np.array([0, 1], complex)):
            for ph in (1, 1j):
                E.append(real(np.kron(ph*e, x2) if k == 0 else np.kron(x1, ph*e)))
        for a, b in itertools.combinations(E, 2): gens.append(wedge(a, b))
print("A3 dim of Lie algebra generated by local great-sphere rotations (N=2): %d (so(8) has 28)" % lie_closure(gens, 8))

# --- B. origin-free generators ---------------------------------------------------------
def su2():
    q = rng.normal(size=4); q /= np.linalg.norm(q)
    return np.array([[q[0]+1j*q[1], q[2]+1j*q[3]], [-q[2]+1j*q[3], q[0]-1j*q[1]]])
def commutant_dim(reps):
    n = reps[0].shape[0]; rows = []
    for U in reps: rows.append(np.kron(U, np.eye(n)) - np.kron(np.eye(n), U.T))
    A = np.vstack(rows); s = np.linalg.svd(A, compute_uv=False)
    return int(np.sum(s < 1e-9))
us = [su2() for _ in range(4)]
print("B1 commutant of SU(2) on C^2: dim %d ; of u(x)u on C^2(x)C^2: dim %d ; of u(x)u(x)u: dim %d"
      % (commutant_dim(us), commutant_dim([np.kron(u, u) for u in us]), commutant_dim([np.kron(np.kron(u, u), u) for u in us])))
sx = np.array([[0, 1], [1, 0]], complex); sy = np.array([[0, -1j], [1j, 0]]); sz = np.diag([1, -1]).astype(complex)
Sw = np.zeros((4, 4)); 
for i in range(2):
    for j in range(2): Sw[2*j+i, 2*i+j] = 1
print("B2 swap = (1 + sigma.sigma)/2 :", np.allclose(Sw, (np.eye(4) + sum(np.kron(s, s) for s in (sx, sy, sz)))/2))

# --- D. velocity space -----------------------------------------------------------------
def bloch(rho): return np.real(np.array([np.trace(rho@s) for s in (sx, sy, sz)]))
def rho_of(r): return (np.eye(2) + r[0]*sx + r[1]*sy + r[2]*sz)/2
def coshd(r1, r2): return (1 - r1@r2)/np.sqrt((1 - r1@r1)*(1 - r2@r2))
errD = errC = errG = 0.0
for _ in range(300):
    r1, r2 = rng.normal(size=3), rng.normal(size=3)
    r1 *= rng.uniform(0, .95)/np.linalg.norm(r1); r2 *= rng.uniform(0, .95)/np.linalg.norm(r2)
    g = rng.normal(size=(2, 2)) + 1j*rng.normal(size=(2, 2)); g /= np.sqrt(np.linalg.det(g))
    f = lambda rho: (g@rho@g.conj().T)/np.trace(g@rho@g.conj().T)
    errD = max(errD, abs(coshd(bloch(f(rho_of(r1))), bloch(f(rho_of(r2)))) - coshd(r1, r2)))
    errG = max(errG, abs(1/np.sqrt(1 - r1@r1) - 1/(2*np.sqrt(np.real(np.linalg.det(rho_of(r1)))))))
    psi = cunit(4); M = psi.reshape(2, 2); rA = bloch(M@M.conj().T); C = 2*abs(np.linalg.det(M))
    errC = max(errC, abs(rA@rA + C**2 - 1))
print("D  filter-invariance of cosh d: %.1e ; gamma = 1/(2 sqrt det rho): %.1e ; r^2 + C^2 = 1: %.1e" % (errD, errG, errC))

