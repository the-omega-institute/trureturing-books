# --- F. octonions (Cayley-Dickson over quaternions) --------------------------------------
def qmul(a, b):
    a0, a1, a2, a3 = a; b0, b1, b2, b3 = b
    return np.array([a0*b0-a1*b1-a2*b2-a3*b3, a0*b1+a1*b0+a2*b3-a3*b2, a0*b2-a1*b3+a2*b0+a3*b1, a0*b3+a1*b2-a2*b1+a3*b0])
def qc(a): return np.array([a[0], -a[1], -a[2], -a[3]])
def omul(x, y):
    a, b, c, d = x[:4], x[4:], y[:4], y[4:]
    return np.concatenate([qmul(a, c) - qmul(qc(d), b), qmul(d, a) + qmul(b, qc(c))])
def oc(x): return np.concatenate([qc(x[:4]), -x[4:]])
def ou():
    v = rng.normal(size=8); return v/np.linalg.norm(v)
eF = {k: 0.0 for k in ["norm mult", "[x,x,z]=z", "[x,z,z]=x", "reflection", "round-trip", "kappa invariance", "associator (nonzero)"]}
T = lambda x, y, z: omul(omul(x, oc(y)), z)
for _ in range(300):
    x, y, z, u, v, w = (ou() for _ in range(6))
    eF["norm mult"] = max(eF["norm mult"], abs(np.linalg.norm(omul(x, y)) - 1))
    eF["[x,x,z]=z"] = max(eF["[x,x,z]=z"], np.abs(T(x, x, z) - z).max())
    eF["[x,z,z]=x"] = max(eF["[x,z,z]=x"], np.abs(T(x, z, z) - x).max())
    eF["reflection"] = max(eF["reflection"], np.abs(T(x, w, x) - (2*(x@w)*x - w)).max())
    eF["round-trip"] = max(eF["round-trip"], abs((1 + w@T(x, w, x))/2 - (x@w)**2))
    eF["kappa invariance"] = max(eF["kappa invariance"], abs(T(x, u, v)@T(y, u, v) - x@y), abs(T(u, v, x)@T(u, v, y) - x@y))
    eF["associator (nonzero)"] = max(eF["associator (nonzero)"], np.abs(T(T(x, y, z), u, v) - T(x, y, T(z, u, v))).max())
for k, e in eF.items(): print("F  %-22s %.2e" % (k, e))

